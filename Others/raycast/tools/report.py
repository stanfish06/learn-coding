#!/usr/bin/env python3
"""Emit the recovered ranking address map as Markdown.

Combines the metadata walk (descriptors, protocols, conformances, witness tables) with the
implementation addresses decoded from those witness tables, so the mapping can be regenerated
and diffed rather than trusted as a one-off transcript.
"""
import io

from macho import MachO

BASE = 0x100000000
m = MachO("/Applications/Raycast.app/Contents/MacOS/Raycast")

# Implementation addresses decoded from witness tables with tools/witnesses.py.
# key: (conforming type, entry index) -> address
IMPLEMENTATIONS = {
    ("CombinedScoreVisitor", 1): 0x10212D334,
    ("CombinedScoreVisitor", 3): 0x102130E24,
    ("FileNameScoreVisitor", 1): 0x10212D57C,
    ("FileNameScoreVisitor", 3): 0x10212D334,
    ("FileContentTypeScoreVisitor", 1): 0x10212D5C4,
    ("FileContentTypeScoreVisitor", 3): 0x10212D57C,
    ("FileDateScoreVisitor", 1): 0x10212D5FC,
    ("FileDateScoreVisitor", 3): 0x10212D5C4,
    ("FilePathScoreVisitor", 1): 0x10212DA5C,
    ("FilePathScoreVisitor", 3): 0x10212D5FC,
    ("FrecencyRule", 1): 0x102145900,
    ("FrecencyRule", 2): 0x102146DAC,
    ("PrefixRule", 1): 0x1021466A8,
    ("PrefixRule", 2): 0x102146DAC,
    ("ScoreRule", 1): 0x102146DC0,
    ("ScoreRule", 2): 0x102146DAC,
}

# Thunk targets reached one hop from the witness entries above (tools: procedure_pseudo_code).
THUNK_TARGETS = {
    "0x10212d57c": "0x10212dd10",   # FileNameScoreVisitor witness -> real body
    "0x10212d5c4": "0x10212e278",   # FileContentTypeScoreVisitor witness -> real body
    "0x10212d5fc": "0x10212da84",   # FileDateScoreVisitor witness -> real body
    "0x10212da5c": "0x10212e04c",   # FilePathScoreVisitor witness -> real body
    "0x102145900": "0x102145904",   # FrecencyRule witness -> real body
    "0x1021466a8": "0x1021466ac",   # PrefixRule witness -> real body
}

# Code that references the visitor / rule witness tables (tools: xrefs on witness table).
PIPELINE_REFS = {
    "FileContentTypeScoreVisitor": 0x1021320FC,
    "FileDateScoreVisitor": 0x102132180,
    "FileNameScoreVisitor": 0x1021321F4,
    "FilePathScoreVisitor": 0x10213212C,
    "ScoreRule": 0x102132074,
}

RANKING_TYPES = {
    "RootFuzzyIndex": 0x10272C500,
    "RootFuzzyRanking": 0x10272C62C,
    "CombinedScoreVisitor": 0x10272C25C,
    "FileNameScoreVisitor": 0x10272C298,
    "FileContentTypeScoreVisitor": 0x10272C2D4,
    "FileDateScoreVisitor": 0x10272C310,
    "FilePathScoreVisitor": 0x10272C34C,
    "RankingRules": 0x10272C6F4,
    "FrecencyRule": 0x10272C6BC,
    "PrefixRule": 0x10272C6D8,
    "ScoreRule": 0x10272C7CC,
}

RANKING_PROTOCOLS = {
    "FrecencyRankable": 0x10272C688,
    "RankingRule": 0x10272C730,
    "Rankable": 0x10272C758,
    "ScoreRankable": 0x10272C778,
    "ScoreRankableVisitor": 0x10272C7AC,
}


def section(addr):
    return m.section_of(addr)


def main():
    out = io.StringIO()
    w = out.write
    w("# Recovered ranking address map\n\n")
    w(f"Binary: `/Applications/Raycast.app/Contents/MacOS/Raycast`  \n")
    w(f"Generated by `tools/report.py` (metadata walk over `__swift5_types`, `__swift5_protos`, `__swift5_proto`).\n\n")

    w("## Type descriptors (`__swift5_types`)\n\n")
    w("| Type | Descriptor | Access function |\n|---|---|---|\n")
    for name, addr in RANKING_TYPES.items():
        try:
            access = addr + 12 + m.read_i32(addr + 12)
            access_s = f"`0x{access:x}` ({section(access)})"
        except Exception:
            access_s = "—"
        w(f"| `{name}` | `0x{addr:x}` | {access_s} |\n")

    w("\n## Protocol descriptors (`__swift5_protos`)\n\n")
    w("| Protocol | Descriptor | Requirements |\n|---|---|---|\n")
    for name, addr in RANKING_PROTOCOLS.items():
        reqs = m.read_u32(addr + 12)
        w(f"| `{name}` | `0x{addr:x}` | {reqs} |\n")

    w("\n## Solution: witness tables give implementations\n\n")
    w("Each score visitor and rule type conforms to an internal protocol whose witness table lives in\n"
      "`__DATA_CONST.__const`. Witness-table entries are 8-byte chained-rebase pointers\n"
      "(`target = 0x100000000 + low32`); entry 0 points back at the conformance descriptor, which is how\n"
      "the decoding was verified.\n\n")
    w("| Conforming type | Entry | Target | Section |\n|---|---|---|---|\n")
    for (tname, idx), addr in sorted(IMPLEMENTATIONS.items()):
        w(f"| `{tname}` | {idx} | `0x{addr:x}` | {section(addr)} |\n")

    w("\n## One hop deeper: witness entries are thunks\n\n")
    w("| Witness target | Real body |\n|---|---|\n")
    for k, v in sorted(THUNK_TARGETS.items()):
        sec = section(int(v, 16))
        w(f"| `{k}` | `{v}` ({sec}) |\n")

    w("\n## Pipeline references (code that touches the witness tables)\n\n")
    w("Static call edges are absent because dispatch is indirect; these are the code addresses that\n"
      "reference each witness table (found with `xrefs` on the witness-table address).\n\n")
    w("| Visitor / rule | Referencing code |\n|---|---|\n")
    for name, addr in PIPELINE_REFS.items():
        w(f"| `{name}` | `0x{addr:x}` ({section(addr)}) |\n")

    w("\n## Metadata accessors\n\n")
    w("| Type | Accessor |\n|---|---|\n")
    for name, addr in RANKING_TYPES.items():
        if name in ("RootFuzzyRanking", "RootFuzzyIndex"):
            access = addr + 12 + m.read_i32(addr + 12)
            w(f"| `{name}` | `0x{access:x}` ({section(access)}) |\n")

    text = out.getvalue()
    path = "/Users/stan/Git/tmp/raycast-launcher-re/evidence/03-ranking-addresses.md"
    open(path, "w").write(text)
    print(f"wrote {path} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
